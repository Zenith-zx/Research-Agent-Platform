CREATE TABLE MARKET_STRESS_ANALYSIS (
    id BIGINT NOT NULL AUTO_INCREMENT,
    symbol VARCHAR(16) NOT NULL,
    analysis_time TIMESTAMP(6) NOT NULL,
    trigger_type VARCHAR(32) NOT NULL,
    rsi6 DECIMAL(12, 4) NULL,
    rsi14 DECIMAL(12, 4) NULL,
    daily_return DECIMAL(12, 4) NULL,
    five_day_return DECIMAL(12, 4) NULL,
    vix DECIMAL(12, 4) NULL,
    us10y DECIMAL(12, 4) NULL,
    brent DECIMAL(14, 4) NULL,
    hyg_return DECIMAL(12, 4) NULL,
    event_stage VARCHAR(32) NULL,
    reversibility VARCHAR(16) NULL,
    fundamental_damage VARCHAR(16) NULL,
    financial_stress VARCHAR(16) NULL,
    event_pricing VARCHAR(32) NULL,
    second_order_pricing VARCHAR(32) NULL,
    seller_exhaustion VARCHAR(16) NULL,
    technical_score INT NULL,
    mean_reversion_score INT NULL,
    action VARCHAR(40) NULL,
    confidence DECIMAL(6, 5) NULL,
    market_is_trading TEXT NULL,
    reasoning_summary TEXT NULL,
    market_snapshot_json LONGTEXT NULL,
    news_json LONGTEXT NULL,
    analysis_json LONGTEXT NULL,
    status VARCHAR(24) NOT NULL,
    error_message VARCHAR(2000) NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    INDEX IDX_MARKET_STRESS_SYMBOL_TIME (symbol, analysis_time),
    INDEX IDX_MARKET_STRESS_STATUS (status)
);
